import { z } from "zod";

/** Longest message a user may send to an agent. */
export const AGENT_MESSAGE_MAX_LENGTH = 2000;

// Control characters (except tab/newline), bidi overrides and zero-width characters are removed:
// they can hide instructions from human reviewers and break rendering.
const INVISIBLE = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F​-‏‪-‮⁠-⁤⁦-⁩﻿]/g;

export const cleanAgentText = (text: string): string => text.replace(INVISIBLE, "").replace(/\r\n?/g, "\n").trim();

/** POST /market/conversations/:id/messages */
export const agentMessageRequestSchema = z
  .object({
    content: z
      .string()
      .transform(cleanAgentText)
      .pipe(z.string().min(1, "Say something first").max(AGENT_MESSAGE_MAX_LENGTH, `Keep it under ${AGENT_MESSAGE_MAX_LENGTH} characters`)),
    /** Generated by the client per message; retrying with the same id never sends it twice. */
    clientMessageId: z.uuid(),
  })
  .strict();
export type AgentMessageRequest = z.infer<typeof agentMessageRequestSchema>;

/** API -> AI agent service (internal): the same request plus the authenticated user. */
export const internalAgentMessageSchema = z
  .object({
    userId: z.uuid(),
    content: z.string().min(1).max(AGENT_MESSAGE_MAX_LENGTH),
    clientMessageId: z.uuid(),
  })
  .strict();
export type InternalAgentMessage = z.infer<typeof internalAgentMessageSchema>;

/** Header carrying the shared secret on API -> AI agent service requests. */
export const INTERNAL_TOKEN_HEADER = "x-entroworld-internal-token";
